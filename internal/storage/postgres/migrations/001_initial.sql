CREATE TABLE users (
 id UUID PRIMARY KEY, email TEXT UNIQUE CHECK(email IS NULL OR email=lower(trim(email))),
 display_name TEXT NOT NULL CHECK(length(display_name) BETWEEN 1 AND 100), avatar_url TEXT NOT NULL DEFAULT '',
 onboarding_completed BOOLEAN NOT NULL DEFAULT false,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE auth_identities (
 id UUID PRIMARY KEY, user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 provider TEXT NOT NULL CHECK(provider IN ('email','yandex','vk')), provider_subject TEXT NOT NULL,
 email TEXT, password_hash TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(provider,provider_subject), UNIQUE(user_id,provider),
 CHECK((provider='email' AND password_hash IS NOT NULL) OR (provider<>'email' AND password_hash IS NULL))
);
CREATE TABLE sessions (
 id TEXT PRIMARY KEY, user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 created_at TIMESTAMPTZ NOT NULL, expires_at TIMESTAMPTZ NOT NULL, last_seen_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX sessions_expiry ON sessions(expires_at);
CREATE TABLE oauth_states (
 id TEXT PRIMARY KEY, provider TEXT NOT NULL, browser_hash TEXT NOT NULL, verifier TEXT NOT NULL,
 link_user_id UUID REFERENCES users(id) ON DELETE CASCADE, expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX oauth_states_expiry ON oauth_states(expires_at);
CREATE TABLE events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 kind TEXT NOT NULL CHECK(kind IN ('task','meeting','reminder')),
 title TEXT NOT NULL CHECK(length(title) BETWEEN 1 AND 500), date TEXT, time TEXT,
 duration_minutes INTEGER NOT NULL DEFAULT 60 CHECK(duration_minutes BETWEEN 5 AND 1440),
 status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','done')),
 created_at TEXT NOT NULL, updated_at TEXT NOT NULL, source_key TEXT,
 description TEXT NOT NULL DEFAULT '', priority TEXT NOT NULL DEFAULT 'normal' CHECK(priority IN ('low','normal','high')),
 external_calendar_id TEXT, location TEXT NOT NULL DEFAULT '', meeting_url TEXT NOT NULL DEFAULT '',
 details TEXT NOT NULL DEFAULT '{}' CHECK(details::jsonb IS NOT NULL), deleted_at TEXT,
 UNIQUE(user_id,source_key)
);
CREATE INDEX events_user_period ON events(user_id,date,time);
CREATE INDEX events_user_kind_status ON events(user_id,kind,status);
CREATE TABLE dialogue_sessions (
 user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE, id TEXT NOT NULL,
 state TEXT NOT NULL CHECK(state::jsonb IS NOT NULL), updated_at TEXT NOT NULL, PRIMARY KEY(user_id,id)
);
CREATE TABLE dialogue_exchanges (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 user_id UUID NOT NULL, session_id TEXT NOT NULL, request_id TEXT NOT NULL,
 message TEXT NOT NULL, response TEXT NOT NULL CHECK(response::jsonb IS NOT NULL), created_at TEXT NOT NULL,
 UNIQUE(user_id,session_id,request_id), FOREIGN KEY(user_id,session_id) REFERENCES dialogue_sessions(user_id,id) ON DELETE CASCADE
);
CREATE TABLE preferences (
 user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE, id TEXT NOT NULL,
 value JSONB NOT NULL CHECK(jsonb_typeof(value)='object'), updated_at TEXT NOT NULL, PRIMARY KEY(user_id,id)
);
CREATE TABLE widget_layouts (
 user_id UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 value JSONB NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(value)='object'), updated_at TEXT NOT NULL
);
CREATE TABLE calendar_connections (
 id UUID PRIMARY KEY, user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 provider TEXT NOT NULL CHECK(provider IN ('yandex','google')), status TEXT NOT NULL DEFAULT 'pending',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(user_id,provider)
);
CREATE TABLE legacy_imports (
 user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE, source_hash TEXT NOT NULL,
 imported_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY(user_id,source_hash)
);
