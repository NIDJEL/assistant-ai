import { test, expect } from '@playwright/test';

test('a new account imports history from settings and can safely repeat it', async ({ page, context }) => {
  const email = `demo-import-${Date.now()}@example.test`;
  const registration = await context.request.post('/api/auth/register', { data: { name: 'Проверка истории', email, password: 'test password 12345', password_confirmation: 'test password 12345' } });
  expect(registration.status()).toBe(201);
  const onboarding = await context.request.post('/api/auth/onboarding', { data: {} });
  expect(onboarding.status()).toBe(200);
  await page.goto('/settings');
  const button = page.getByRole('button', { name: 'Загрузить примеры', exact: true });
  await button.click();
  await expect(page.getByRole('status').filter({ hasText: 'Добавлено записей: 1000' })).toBeVisible();
  await expect(button).toBeEnabled();
  await button.click();
  await expect(page.getByRole('status').filter({ hasText: 'Повторных записей не добавлено' })).toBeVisible();
  await page.getByLabel('Свой CSV-файл').setInputFiles('../data/voice_assistant_events_1000.csv');
  await page.getByRole('button', { name: 'Загрузить свой CSV', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Повторных записей не добавлено' })).toBeVisible();
  await page.reload();
  const found = await context.request.get('/api/tasks?q=контракт&limit=10');
  expect(found.status()).toBe(200);
  expect((await found.json()).events.length).toBeGreaterThan(0);
});

test('custom CSV imports atomically and can be repeated under another name', async ({ page, context }) => {
  const email = `csv-import-${Date.now()}@example.test`;
  const registration = await context.request.post('/api/auth/register', { data: { name: 'Проверка CSV', email, password: 'test password 12345', password_confirmation: 'test password 12345' } });
  expect(registration.status()).toBe(201);
  await context.request.post('/api/auth/onboarding', { data: {} });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/settings');
  const input = page.getByLabel('Свой CSV-файл');
  const button = page.getByRole('button', { name: 'Загрузить свой CSV', exact: true });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Скачать образец CSV' }).click();
  expect((await downloadPromise).suggestedFilename()).toBe('events-template.csv');
  const csv = 'id,date,time,text\n1,2026-12-01,10:00,Подготовить отчёт из CSV\n2,2026-12-02,15:00,Встреча с командой из CSV\n';
  await input.setInputFiles({ name: 'mine.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: test.info().outputPath('csv-import-mobile.png'), fullPage: true });
  const before = await context.request.get('/api/events');
  expect((await before.json()).total).toBe(0);
  await button.click();
  await expect(page.getByRole('status').filter({ hasText: 'Добавлено записей: 2' })).toBeVisible();
  const events = await context.request.get('/api/events');
  expect((await events.json()).total).toBe(2);
  await input.setInputFiles({ name: 'renamed.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) });
  await button.click();
  await expect(page.getByRole('status').filter({ hasText: 'Повторных записей не добавлено' })).toBeVisible();
  await input.setInputFiles({ name: 'bad.csv', mimeType: 'text/csv', buffer: Buffer.from('id,date,time,text\n3,2026-12-03,10:00,Верная строка\n4,2026-02-31,10:00,Ошибка\n') });
  await button.click();
  await expect(page.getByRole('alert').filter({ hasText: 'строке 3' })).toBeVisible();
  const after = await context.request.get('/api/events');
  expect((await after.json()).total).toBe(2);
});
